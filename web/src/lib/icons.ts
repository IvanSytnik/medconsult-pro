import {
  Award,
  BadgeCheck,
  Bone,
  Building2,
  Calendar,
  Car,
  CheckCircle2,
  ClipboardList,
  Clock,
  Crown,
  Diamond,
  FlaskConical,
  Globe,
  Headphones,
  HeartPulse,
  Hotel,
  Infinity as InfinityIcon,
  Mail,
  MapPin,
  MessageCircle,
  Microscope,
  Palmtree,
  Phone,
  Scissors,
  Shield,
  Smile,
  Sparkles,
  Sprout,
  Star,
  Stethoscope,
  Syringe,
  Target,
  TrendingUp,
  Users,
  Wallet,
  Wrench,
  Zap,
  type LucideIcon,
} from 'lucide-react'
import type { IconName } from './icon-names'

const ICONS: Record<IconName, LucideIcon> = {
  smile: Smile,
  crown: Crown,
  award: Award,
  syringe: Syringe,
  scissors: Scissors,
  wrench: Wrench,
  diamond: Diamond,
  sparkles: Sparkles,
  bone: Bone,
  building: Building2,
  'check-circle': CheckCircle2,
  stethoscope: Stethoscope,
  wallet: Wallet,
  clock: Clock,
  palmtree: Palmtree,
  shield: Shield,
  users: Users,
  'heart-pulse': HeartPulse,
  microscope: Microscope,
  target: Target,
  'trending-up': TrendingUp,
  calendar: Calendar,
  sprout: Sprout,
  'badge-check': BadgeCheck,
  zap: Zap,
  star: Star,
  flask: FlaskConical,
  globe: Globe,
  hotel: Hotel,
  car: Car,
  headphones: Headphones,
  'clipboard-list': ClipboardList,
  mail: Mail,
  phone: Phone,
  'message-circle': MessageCircle,
  'map-pin': MapPin,
  infinity: InfinityIcon,
}

/** Resolves a CMS icon key to a lucide component; unknown or empty keys fall back to a check mark. */
export function getIcon(name: string | null | undefined): LucideIcon {
  return (name && ICONS[name as IconName]) || CheckCircle2
}
